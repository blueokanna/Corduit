#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MethodKind {
    None,
    Rc4,
    /// RC4 whose effective key is `MD5(key || iv)`; the IV is still sent.
    Rc4Md5,
    Cfb,
    Ctr,
    /// The original 64-bit-nonce ChaCha.
    Chacha20,
    /// RFC 8439 ChaCha.
    Chacha20Ietf,
    Salsa20,
}

/// An SSR method's shape: how long a key and an IV it needs, and what to build
/// from them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SsrMethod {
    key_len: usize,
    iv_len: usize,
    kind: MethodKind,
}

impl SsrMethod {
    /// Parse a ShadowsocksR method name.
    ///
    /// The refusal branches come before the catch-all so a user whose profile
    /// names something we cannot carry gets the *reason*, not "unknown method".
    pub fn parse(name: &str) -> Result<Self> {
        let lower = name.trim().to_ascii_lowercase();
        let (key_len, iv_len, kind) = match lower.as_str() {
            "none" | "plain" => (0, 0, MethodKind::None),
            "rc4" => (16, 0, MethodKind::Rc4),
            "rc4-md5" => (16, 16, MethodKind::Rc4Md5),
            "aes-128-cfb" => (16, 16, MethodKind::Cfb),
            "aes-192-cfb" => (24, 16, MethodKind::Cfb),
            "aes-256-cfb" => (32, 16, MethodKind::Cfb),
            "aes-128-ctr" => (16, 16, MethodKind::Ctr),
            "aes-192-ctr" => (24, 16, MethodKind::Ctr),
            "aes-256-ctr" => (32, 16, MethodKind::Ctr),
            "chacha20" => (32, 8, MethodKind::Chacha20),
            "chacha20-ietf" => (32, 12, MethodKind::Chacha20Ietf),
            "salsa20" => (32, 8, MethodKind::Salsa20),
            "table" => {
                return Err(Error::config(
                    "SSR method `table` is an 8-bit substitution table with no key and no IV; \
                     it is not encryption and is not implemented",
                ))
            }
            other if other.ends_with("-gcm") || other.ends_with("-poly1305") => {
                return Err(Error::config(format!(
                    "SSR method `{other}` is an AEAD method; use the `shadowsocks` outbound, \
                     which implements the AEAD framing, rather than the SSR plugin path"
                )))
            }
            other
                if [
                    "bf-",
                    "camellia-",
                    "cast5-",
                    "des-",
                    "idea-",
                    "rc2-",
                    "seed-",
                    "aes-128-cfb8",
                    "aes-192-cfb8",
                    "aes-256-cfb8",
                    "aes-128-ofb",
                    "aes-192-ofb",
                    "aes-256-ofb",
                ]
                .iter()
                .any(|family| other.starts_with(family)) =>
            {
                return Err(Error::config(format!(
                    "SSR method `{other}` needs a block cipher this build does not carry \
                     (Blowfish / Camellia / CAST5 / DES / IDEA / RC2 / SEED); the aes-*, \
                     chacha20* and salsa20 families are available"
                )))
            }
            other => {
                return Err(Error::config(format!(
                    "Unknown SSR method `{other}`; supported: none, rc4, rc4-md5, \
                     aes-{{128,192,256}}-{{cfb,ctr}}, chacha20, chacha20-ietf, salsa20"
                )))
            }
        };
        Ok(Self {
            key_len,
            iv_len,
            kind,
        })
    }

    /// Key length in bytes.
    pub fn key_len(self) -> usize {
        self.key_len
    }

    /// IV length in bytes (0 for `rc4` and `none`, which send none).
    pub fn iv_len(self) -> usize {
        self.iv_len
    }
}

/// `EVP_BytesToKey`: OpenSSL's MD5 chain, shared by Shadowsocks and SSR.
///
/// `D_i = MD5(D_{i-1} || password)` with `D_0` empty; the key and IV are
/// consecutive slices of the concatenation. Returning both from one function
/// matters — an implementation that restarted the chain for the IV would derive
/// a self-consistent but incompatible pair.
pub(crate) fn evp_bytes_to_key(password: &[u8], key_len: usize, iv_len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(key_len + iv_len);
    let mut previous: Vec<u8> = Vec::new();
    while out.len() < key_len + iv_len {
        let mut hasher = Md5::new();
        hasher.update(&previous);
        hasher.update(password);
        let digest = hasher.finalize();
        previous = digest.to_vec();
        out.extend_from_slice(&digest);
    }
    out.truncate(key_len + iv_len);
    out
}

/// One direction's cipher state. A stream cipher: the same operation encrypts
/// and decrypts.
enum SsrCipher {
    None,
    Rc4(Rc4),
    Cfb(Cfb128),
    Ctr(Ctr),
    Chacha20(ChaCha20Legacy),
    Chacha20Ietf(ChaCha20),
    Salsa20(Salsa20),
}

impl SsrCipher {
    fn apply(&mut self, buf: &mut [u8]) {
        match self {
            Self::None => {}
            Self::Rc4(cipher) => cipher.apply_keystream(buf),
            Self::Cfb(cipher) => cipher.encrypt(buf),
            Self::Ctr(cipher) => cipher.apply_keystream(buf),
            Self::Chacha20(cipher) => cipher.apply_keystream(buf),
            Self::Chacha20Ietf(cipher) => cipher.apply_keystream(buf),
            Self::Salsa20(cipher) => cipher.apply_keystream(buf),
        }
    }
}

/// The method plus the key material derived from the password — everything
/// needed to build either direction's cipher once that direction's IV is known.
struct SsrCrypto {
    method: SsrMethod,
    key: Vec<u8>,
    iv: Vec<u8>,
}

impl SsrCrypto {
    fn new(method: SsrMethod, password: &[u8]) -> Self {
        let material = evp_bytes_to_key(password, method.key_len(), method.iv_len());
        let (key, iv) = material.split_at(method.key_len());
        Self {
            method,
            key: key.to_vec(),
            iv: iv.to_vec(),
        }
    }

    /// Build a cipher for `iv`.
    ///
    /// `rc4-md5` is why this takes the IV rather than just the key: its
    /// effective key is `MD5(key || iv)`, so the two directions — which have
    /// different IVs — get different RC4 states from one master key.
    fn cipher(&self, iv: &[u8]) -> Result<SsrCipher> {
        let bad =
            |what: &str| Error::config(format!("SSR {what} length does not match the method"));
        Ok(match self.method.kind {
            MethodKind::None => SsrCipher::None,
            MethodKind::Rc4 => SsrCipher::Rc4(Rc4::new(&self.key).map_err(|_| bad("key"))?),
            MethodKind::Rc4Md5 => {
                let mut hasher = Md5::new();
                hasher.update(&self.key);
                hasher.update(iv);
                let digest = hasher.finalize();
                SsrCipher::Rc4(Rc4::new(&digest).map_err(|_| bad("key"))?)
            }
            MethodKind::Cfb => {
                SsrCipher::Cfb(Cfb128::new(&self.key, iv).map_err(|_| bad("key/IV"))?)
            }
            MethodKind::Ctr => SsrCipher::Ctr(Ctr::new(&self.key, iv).map_err(|_| bad("key/IV"))?),
            MethodKind::Chacha20 => {
                let (key, nonce) = fixed::<32, 8>(&self.key, iv)?;
                SsrCipher::Chacha20(ChaCha20Legacy::new(&key, &nonce, 0))
            }
            MethodKind::Chacha20Ietf => {
                let (key, nonce) = fixed::<32, 12>(&self.key, iv)?;
                SsrCipher::Chacha20Ietf(ChaCha20::new(&key, &nonce, 0))
            }
            MethodKind::Salsa20 => {
                let (key, nonce) = fixed::<32, 8>(&self.key, iv)?;
                SsrCipher::Salsa20(Salsa20::new(&key, &nonce, 0))
            }
        })
    }
}

/// Copy a key and an IV into fixed-size arrays, refusing a length mismatch.
///
/// The lengths are already guaranteed by [`SsrMethod`]; the function exists so
/// the guarantee is checked once instead of being asserted by a `copy_from_slice`
/// that would panic on a future table edit.
fn fixed<const K: usize, const N: usize>(key: &[u8], iv: &[u8]) -> Result<([u8; K], [u8; N])> {
    let mut key_out = [0u8; K];
    let mut iv_out = [0u8; N];
    if key.len() != K || iv.len() != N {
        return Err(Error::config(format!(
            "SSR cipher expects a {K}-byte key and a {N}-byte IV, got {} and {}",
            key.len(),
            iv.len()
        )));
    }
    key_out.copy_from_slice(key);
    iv_out.copy_from_slice(iv);
    Ok((key_out, iv_out))
}

