/// Which obfs plugin is in use.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SsrObfs {
    /// `plain`: nothing on top of the cipher.
    Plain,
    /// `http_simple`: a `GET` whose URI carries the first bytes hex-escaped.
    HttpSimple { host: String, uri: String },
    /// `http_post`: the same head, with the bytes in the body instead.
    HttpPost { host: String, uri: String },
    /// `tls1.2_ticket_auth`: a fabricated handshake, then TLS-record framing.
    Tls12TicketAuth { host: String },
}

impl SsrObfs {
    /// Parse the plugin name; `host` comes from the profile's `obfs-host`.
    pub fn parse(name: &str, host: Option<String>) -> Result<Self> {
        let host = host.unwrap_or_else(|| "bing.com".to_string());
        match name.trim().to_ascii_lowercase().as_str() {
            "" | "plain" => Ok(Self::Plain),
            "http_simple" => Ok(Self::HttpSimple {
                host,
                uri: "/".to_string(),
            }),
            "http_post" => Ok(Self::HttpPost {
                host,
                uri: "/".to_string(),
            }),
            "tls1.2_ticket_auth" | "tls1.2_ticket_fastauth" => Ok(Self::Tls12TicketAuth { host }),
            "random_head" => Err(Error::config(
                "SSR obfs `random_head` is not implemented: its first packet is a random string \
                 plus the complement of its CRC-32, but the plugin then holds the client's whole \
                 stream back until the server's own random packet arrives, and the relay's write \
                 path has no second buffer to hold it in",
            )),
            other => Err(Error::config(format!(
                "Unknown SSR obfs `{other}`; supported: plain, http_simple, http_post, \
                 tls1.2_ticket_auth"
            ))),
        }
    }

    fn name(&self) -> &'static str {
        match self {
            Self::Plain => "plain",
            Self::HttpSimple { .. } => "http_simple",
            Self::HttpPost { .. } => "http_post",
            Self::Tls12TicketAuth { .. } => "tls1.2_ticket_auth",
        }
    }
}

/// User agents the HTTP obfs draws from, mirroring the reference's list: a
/// constant user agent across a deployment is a fingerprint of its own.
const HTTP_OBFS_AGENTS: &[&str] = &[
    "Mozilla/5.0 (Windows NT 6.1; WOW64; rv:40.0) Gecko/20100101 Firefox/40.0",
    "Mozilla/5.0 (Windows NT 6.3; WOW64; rv:44.0) Gecko/20100101 Firefox/44.0",
    "Mozilla/5.0 (Windows NT 10.0; WOW64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/41.0.2228.0 Safari/537.36",
    "Mozilla/5.0 (Macintosh; Intel Mac OS X 10.11; rv:42.0) Gecko/20100101 Firefox/42.0",
    "Mozilla/5.0 (iPhone; CPU iPhone OS 9_2 like Mac OS X) AppleWebKit/601.1.46 (KHTML, like Gecko) Version/9.0 Mobile/13C75 Safari/601.1",
];

/// The obfs host the first packet announces.
///
/// The reference drops a host whose last character is a digit (an address in an
/// SNI is a giveaway) and draws at random from a comma-separated list, so that a
/// deployment behind several names does not vary in lockstep.
fn pick_obfs_host(configured: &str) -> String {
    if configured.as_bytes().last().is_some_and(u8::is_ascii_digit) {
        return String::new();
    }
    let hosts: Vec<&str> = configured.split(',').map(str::trim).collect();
    let mut pick = [0u8; 1];
    fill_random(&mut pick);
    hosts[usize::from(pick[0]) % hosts.len()].to_string()
}

/// The `multipart/form-data` boundary `http_post` announces.
fn random_boundary() -> String {
    const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    let mut out = String::with_capacity(32);
    while out.len() < 32 {
        let mut byte = [0u8; 1];
        fill_random(&mut byte);
        // Rejection sampling: folding 256 onto 62 would bias the first eight
        // characters of every boundary.
        if usize::from(byte[0]) < 62 * 4 {
            out.push(char::from(ALPHABET[usize::from(byte[0]) % ALPHABET.len()]));
        }
    }
    out
}

/// The obfs state for one connection.
struct SsrObfsState {
    obfs: SsrObfs,
    wrapped: bool,
    unwrapped: bool,
    /// `tls1.2_ticket_auth`'s 32-byte client id: the session id the ClientHello
    /// carries, which the peer echoes and which salts every handshake MAC.
    client_id: [u8; 32],
    /// Bytes received but not yet handed to the cipher: the preamble, and
    /// (for the TLS obfs) records that have not arrived in full.
    pending: Vec<u8>,
    agent: &'static str,
    boundary: String,
    /// The server's port. The fake head names it unless it is 80, which is what
    /// the reference does and what a port-80 listener would expect to see.
    server_port: u16,
}

impl SsrObfsState {
    fn new(obfs: SsrObfs, server_port: u16) -> Self {
        let mut client_id = [0u8; 32];
        fill_random(&mut client_id);
        let mut pick = [0u8; 1];
        fill_random(&mut pick);
        Self {
            obfs,
            wrapped: false,
            unwrapped: false,
            client_id,
            pending: Vec::new(),
            agent: HTTP_OBFS_AGENTS[usize::from(pick[0]) % HTTP_OBFS_AGENTS.len()],
            boundary: random_boundary(),
            server_port,
        }
    }

    /// The `tls1.2_ticket_auth` handshake MAC key: `key || client_id`.
    fn tls_mac_key(&self, key: &[u8]) -> Vec<u8> {
        let mut out = Vec::with_capacity(key.len() + 32);
        out.extend_from_slice(key);
        out.extend_from_slice(&self.client_id);
        out
    }

    /// Wrap an outgoing buffer, which is only ever the first one: everything
    /// after it is a plain data frame.
    ///
    /// `head_len` is the address header's length and `iv_len` the cipher's IV
    /// length: the HTTP obfs moves their sum (plus up to 64 bytes) out of the
    /// body and into the request line, so the IV and the header do not sit at a
    /// fixed offset where a middlebox could count them.
    fn wrap(&mut self, buf: &[u8], key: &[u8], head_len: usize, iv_len: usize) -> Vec<u8> {
        if self.wrapped {
            return match &self.obfs {
                SsrObfs::Tls12TicketAuth { .. } => tls_records(buf),
                _ => buf.to_vec(),
            };
        }
        self.wrapped = true;

        match &self.obfs {
            SsrObfs::Plain => buf.to_vec(),
            SsrObfs::HttpSimple { host, uri } | SsrObfs::HttpPost { host, uri } => {
                let post = matches!(self.obfs, SsrObfs::HttpPost { .. });
                let head_size = iv_len + head_len;
                let in_uri = if buf.len() > head_size + 64 {
                    head_size + rand_below(65)
                } else {
                    buf.len()
                };
                let host = pick_obfs_host(host);
                let mut out = self.http_head(post, &host, uri, &buf[..in_uri]);
                out.extend_from_slice(&buf[in_uri..]);
                out
            }
            SsrObfs::Tls12TicketAuth { host } => {
                let host = pick_obfs_host(host);
                let mut out = self.tls_client_hello(key, &host);
                // The fabricated `ChangeCipherSpec` and `Finished`, then the MAC
                // over exactly those two records, and only then the payload —
                // itself wrapped in application-data records.
                //
                // The `Finished` record declares 32 payload bytes and sends 22
                // of them; the reader derives the body length as
                // `declared - 10`, which is why the two numbers stay apart.
                let mut tail = vec![0x14, 0x03, 0x03, 0x00, 0x01, 0x01];
                tail.extend_from_slice(&[0x16, 0x03, 0x03, 0x00, 0x20]);
                tail.extend_from_slice(&random_bytes(22));
                let mac = hmac_truncated::<Sha1>(&self.tls_mac_key(key), &tail, 10);
                tail.extend_from_slice(&mac);
                out.extend_from_slice(&tail);
                out.extend_from_slice(&tls_records(buf));
                out
            }
        }
    }

    /// The fake request head: the first `uri_bytes` ride in the request line,
    /// percent-encoded, and the peer's decoder reads them back out.
    fn http_head(&self, post: bool, host: &str, uri: &str, uri_bytes: &[u8]) -> Vec<u8> {
        let mut head = String::with_capacity(512 + uri_bytes.len() * 3);
        head.push_str(if post { "POST " } else { "GET " });
        head.push_str(uri);
        for byte in uri_bytes {
            head.push('%');
            head.push_str(&format!("{byte:02x}"));
        }
        head.push_str(" HTTP/1.1\r\n");
        if self.server_port != 80 && self.server_port != 0 {
            head.push_str(&format!("Host: {host}:{}\r\n", self.server_port));
        } else {
            head.push_str(&format!("Host: {host}\r\n"));
        }
        head.push_str(&format!("User-Agent: {}\r\n", self.agent));
        head.push_str(
            "Accept: text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8\r\n",
        );
        head.push_str("Accept-Language: en-US,en;q=0.8\r\n");
        head.push_str("Accept-Encoding: gzip, deflate\r\n");
        if post {
            head.push_str(&format!(
                "Content-Type: multipart/form-data; boundary={}\r\n",
                self.boundary
            ));
        }
        head.push_str("DNT: 1\r\n");
        head.push_str("Connection: keep-alive\r\n\r\n");
        head.into_bytes()
    }

    /// The fabricated ClientHello (`obfs_tls.py` · `client_encode`).
    fn tls_client_hello(&self, key: &[u8], host: &str) -> Vec<u8> {
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs() as u32)
            .unwrap_or(0);
        let mut verifyid = now.to_be_bytes().to_vec();
        verifyid.extend_from_slice(&random_bytes(18));
        let mac = hmac_truncated::<Sha1>(&self.tls_mac_key(key), &verifyid, 10);

        let mut body = vec![0x03, 0x03];
        body.extend_from_slice(&verifyid);
        body.extend_from_slice(&mac);
        body.push(0x20);
        body.extend_from_slice(&self.client_id);
        // The reference's exact cipher-suite list and compression byte: a
        // client that rewrote these would have a fingerprint of its own.
        body.extend_from_slice(&[
            0x00, 0x1c, 0xc0, 0x2b, 0xc0, 0x2f, 0xcc, 0xa9, 0xcc, 0xa8, 0xcc, 0x14, 0xcc, 0x13,
            0xc0, 0x0a, 0xc0, 0x14, 0xc0, 0x09, 0xc0, 0x13, 0x00, 0x9c, 0x00, 0x35, 0x00, 0x2f,
            0x00, 0x0a, 0x01, 0x00,
        ]);

        // Extensions in the reference's order; the ticket is random padding of a
        // size drawn from its 16-byte-block rule.
        let ticket = random_bytes((rand_below(17) + 8) * 16);
        let host_bytes = host.as_bytes();
        let mut extensions = Vec::new();
        extensions.extend_from_slice(&[0xff, 0x01, 0x00, 0x01, 0x00]);
        extensions.extend_from_slice(&[0x00, 0x00]);
        extensions.extend_from_slice(&((host_bytes.len() + 5) as u16).to_be_bytes());
        extensions.extend_from_slice(&((host_bytes.len() + 3) as u16).to_be_bytes());
        extensions.push(0x00);
        extensions.extend_from_slice(&(host_bytes.len() as u16).to_be_bytes());
        extensions.extend_from_slice(host_bytes);
        extensions.extend_from_slice(&[0x00, 0x17, 0x00, 0x00]);
        extensions.extend_from_slice(&[0x00, 0x23]);
        extensions.extend_from_slice(&(ticket.len() as u16).to_be_bytes());
        extensions.extend_from_slice(&ticket);
        extensions.extend_from_slice(&[
            0x00, 0x0d, 0x00, 0x16, 0x00, 0x14, 0x06, 0x01, 0x06, 0x03, 0x05, 0x01, 0x05, 0x03,
            0x04, 0x01, 0x04, 0x03, 0x03, 0x01, 0x03, 0x03, 0x02, 0x01, 0x02, 0x03, 0x00, 0x05,
            0x00, 0x05, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x12, 0x00, 0x00, 0x75, 0x50, 0x00,
            0x00, 0x00, 0x0b, 0x00, 0x02, 0x01, 0x00, 0x00, 0x0a, 0x00, 0x06, 0x00, 0x04, 0x00,
            0x17, 0x00, 0x18,
        ]);

        let hs_len = body.len() + extensions.len() + 2;
        let mut record = vec![0x16, 0x03, 0x01];
        let mut handshake = vec![0x01, 0x00];
        handshake.extend_from_slice(&(hs_len as u16).to_be_bytes());
        handshake.extend_from_slice(&body);
        handshake.extend_from_slice(&(extensions.len() as u16).to_be_bytes());
        handshake.extend_from_slice(&extensions);
        record.extend_from_slice(&(handshake.len() as u16).to_be_bytes());
        record.extend_from_slice(&handshake);
        record
    }

    /// Check the peer's fabricated `ServerHello`, then its
    /// `ChangeCipherSpec` / `Finished` pair and the MAC that seals them.
    ///
    /// `Ok(false)` means "not enough bytes yet"; the records are only dropped
    /// once the MAC has been checked, so a retry re-reads them from the start.
    fn verify_server_handshake(&mut self, key: &[u8]) -> Result<bool> {
        let buf = &self.pending;
        if buf.len() < 5 {
            return Ok(false);
        }
        if buf[..3] != [0x16, 0x03, 0x03] {
            return Err(Error::protocol(
                "SSR obfs: the fabricated handshake did not open with a ServerHello record",
            ));
        }
        // `ServerHello` = record(5) || 02 00 || u16 len || version || auth(32) ||
        //                 20 || session id(32) || ten bytes of suites + SCSV.
        let hello_end = 5 + usize::from(u16::from_be_bytes([buf[3], buf[4]]));
        const HELLO_MIN: usize = 76;
        if hello_end < HELLO_MIN {
            return Err(Error::protocol("SSR obfs: truncated ServerHello"));
        }
        if buf.len() < hello_end {
            return Ok(false);
        }
        if buf[5..7] != [0x02, 0x00] || buf[9..11] != [0x03, 0x03] {
            return Err(Error::protocol("SSR obfs: malformed ServerHello"));
        }
        let auth_mac = hmac_truncated::<Sha1>(&self.tls_mac_key(key), &buf[11..33], 10);
        if auth_mac[..] != buf[33..43] {
            return Err(Error::protocol(
                "SSR obfs: the ServerHello failed its handshake MAC",
            ));
        }
        if buf[43] != 0x20 || buf[44..76] != self.client_id[..] {
            return Err(Error::protocol(
                "SSR obfs: the ServerHello did not echo this connection's session id",
            ));
        }

        let mut pos = hello_end;
        // A session ticket may sit between the ServerHello and the CCS.
        if buf.len() < pos + 5 {
            return Ok(false);
        }
        if buf[pos] == 0x16 {
            pos += 5 + usize::from(u16::from_be_bytes([buf[pos + 3], buf[pos + 4]]));
            if buf.len() < pos + 6 {
                return Ok(false);
            }
        }
        if buf[pos..pos + 3] != [0x14, 0x03, 0x03] || buf[pos + 3..pos + 6] != [0x00, 0x01, 0x01] {
            return Err(Error::protocol(
                "SSR obfs: expected a ChangeCipherSpec record",
            ));
        }
        pos += 6;

        if buf.len() < pos + 5 {
            return Ok(false);
        }
        if buf[pos..pos + 3] != [0x16, 0x03, 0x03] {
            return Err(Error::protocol("SSR obfs: expected a Finished record"));
        }
        // The `Finished` declared length is ten bytes longer than the body that
        // follows it, so the body is `declared - 10`; the peer's own parser
        // makes the same subtraction.
        let declared = usize::from(u16::from_be_bytes([buf[pos + 3], buf[pos + 4]]));
        if declared < 10 {
            return Err(Error::protocol(
                "SSR obfs: the Finished record is shorter than its own length field",
            ));
        }
        pos += 5 + (declared - 10);
        if buf.len() < pos + 10 {
            return Ok(false);
        }

        let bundle_mac = hmac_truncated::<Sha1>(&self.tls_mac_key(key), &buf[..pos], 10);
        if bundle_mac[..] != buf[pos..pos + 10] {
            return Err(Error::protocol(
                "SSR obfs: the fabricated handshake failed its MAC",
            ));
        }
        self.pending.drain(..pos + 10);
        Ok(true)
    }

    /// Feed raw bytes, returning whatever the cipher layer can now process.
    ///
    /// Everything that arrives is buffered, so a preamble or a record split
    /// across reads is handled without losing a partial record. An empty return
    /// means "nothing complete yet".
    fn unwrap(&mut self, buf: &[u8], key: &[u8]) -> Result<Vec<u8>> {
        self.pending.extend_from_slice(buf);

        if !self.unwrapped {
            match &self.obfs {
                SsrObfs::Plain => {}
                SsrObfs::HttpSimple { .. } | SsrObfs::HttpPost { .. } => {
                    // The peer's fake response head ends at a blank line; the
                    // stream starts right after it. Nothing is decoded here:
                    // the percent-encoded bytes only travel the other way.
                    match find_head_end(&self.pending) {
                        Some(end) => {
                            self.pending.drain(..end);
                        }
                        None => {
                            if self.pending.len() > MAX_OBFS_PREAMBLE {
                                return Err(Error::protocol(
                                    "SSR obfs: the fake HTTP response head exceeded the cap",
                                ));
                            }
                            return Ok(Vec::new());
                        }
                    }
                }
                SsrObfs::Tls12TicketAuth { .. } => {
                    if !self.verify_server_handshake(key)? {
                        if self.pending.len() > MAX_OBFS_PREAMBLE {
                            return Err(Error::protocol(
                                "SSR obfs: the fabricated TLS handshake exceeded the cap",
                            ));
                        }
                        return Ok(Vec::new());
                    }
                }
            }
            self.unwrapped = true;
        }

        if matches!(self.obfs, SsrObfs::Tls12TicketAuth { .. }) {
            // The data phase is record-framed for the life of the connection,
            // so complete records are drained and a partial one stays buffered.
            let mut out = Vec::new();
            loop {
                if self.pending.len() < 5 {
                    break;
                }
                if self.pending[..3] != [0x17, 0x03, 0x03] {
                    return Err(Error::protocol(format!(
                        "SSR obfs: unexpected TLS record type 0x{:02x} in the data phase",
                        self.pending[0]
                    )));
                }
                let length = usize::from(u16::from_be_bytes([self.pending[3], self.pending[4]]));
                if self.pending.len() < 5 + length {
                    break;
                }
                out.extend_from_slice(&self.pending[5..5 + length]);
                self.pending.drain(..5 + length);
            }
            if self.pending.len() > MAX_PENDING {
                return Err(Error::protocol(
                    "SSR obfs: partial TLS record exceeded the cap",
                ));
            }
            Ok(out)
        } else {
            Ok(std::mem::take(&mut self.pending))
        }
    }
}

/// Index just past the blank line that ends an HTTP head.
fn find_head_end(buf: &[u8]) -> Option<usize> {
    buf.windows(4).position(|w| w == b"\r\n\r\n").map(|i| i + 4)
}

/// Wrap `buf` in `17 03 03` application-data records.
///
/// Below 2048 bytes it is one record. Above it, records are cut at
/// `u16BE(rand) % 4096 + 100`, which is what keeps a long upload from arriving
/// as a ladder of identical record sizes.
fn tls_records(buf: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(buf.len() + 5 * (buf.len() / 2048 + 1));
    let mut rest = buf;
    while rest.len() > 2048 {
        let mut draw = [0u8; 2];
        fill_random(&mut draw);
        let size = (usize::from(u16::from_be_bytes(draw)) % 4096 + 100).min(rest.len());
        out.extend_from_slice(&[0x17, 0x03, 0x03]);
        out.extend_from_slice(&(size as u16).to_be_bytes());
        out.extend_from_slice(&rest[..size]);
        rest = &rest[size..];
    }
    if !rest.is_empty() {
        out.extend_from_slice(&[0x17, 0x03, 0x03]);
        out.extend_from_slice(&(rest.len() as u16).to_be_bytes());
        out.extend_from_slice(rest);
    }
    out
}

