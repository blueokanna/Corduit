    /// Both random-prefix encoders must agree with the reader that skips them:
    /// the value a prefix stores is its own length, so the reader lands exactly
    /// on the first payload byte.
    ///
    /// That is the only reason the escape forms are interchangeable, and it is
    /// why the long form's field counts its two length bytes as well.
    #[test]
    fn the_random_prefix_encodings_agree_with_the_reader() {
        let proto = state(SsrProtocol::AuthSha1V4, "aes-128-cfb", "");
        for buf_size in [0usize, 100, 400, 401, 1200, 1201, 8199] {
            let prefix = proto.rnd_data_sha1(buf_size);
            let start = if prefix[0] < 0xFF {
                assert_eq!(
                    usize::from(prefix[0]),
                    prefix.len(),
                    "the short form stores its own length ({buf_size})"
                );
                usize::from(prefix[0])
            } else {
                assert!(
                    prefix.len() >= 3,
                    "the long form needs its two length bytes"
                );
                usize::from(u16::from_be_bytes([prefix[1], prefix[2]]))
            };
            // The data frame's prefix starts at offset 4 (length + CRC), so the
            // skip must land at its end.
            assert_eq!(
                start,
                prefix.len(),
                "sha1 prefix for a {buf_size}-byte buffer"
            );
        }

        // `auth_aes128` writes the same field little-endian, and keeps both
        // forms at `rnd_len + 1` bytes by sending two random bytes fewer than
        // the field counts.
        for rnd_len in [0usize, 1, 127, 128, 200, 511] {
            let prefix = rnd_prefix_aes(rnd_len);
            assert_eq!(prefix.len(), rnd_len + 1, "aes {rnd_len}");
            let start = if prefix[0] < 0xFF {
                usize::from(prefix[0])
            } else {
                usize::from(u16::from_le_bytes([prefix[1], prefix[2]]))
            };
            assert_eq!(start, prefix.len(), "aes {rnd_len} stores its own length");
        }
    }

