/// The Shadowsocks address header: `ATYP || ADDR || PORT`, no length prefix.
fn address_header(target: &TargetAddr) -> Result<Vec<u8>> {
    let address = crate::protocol::Address::from(target);
    let mut buf = Vec::with_capacity(20);
    address
        .write_address_to(&mut buf)
        .map_err(|e| Error::protocol(format!("SSR address header: {e}")))?;
    buf.extend_from_slice(&target.port().to_be_bytes());
    Ok(buf)
}

/// The header's own length, which both the protocol layer and the HTTP obfs
/// need (the first frame keeps the header together with the handshake, and the
/// HTTP head sizes its URI around it).
fn address_header_len(buf: &[u8]) -> usize {
    match buf.first().map(|b| b & 0x0F) {
        Some(1) => 7,
        Some(4) => 19,
        Some(3) if buf.len() >= 2 => 4 + usize::from(buf[1]),
        Some(3) => 4,
        _ => 30,
    }
}

