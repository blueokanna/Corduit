    /// The whole write path, both directions, with the layer order enforced:
    /// the obfs sees `IV || ciphertext`, and the reader gets the plaintext back.
    ///
    /// The HTTP and TLS obfs plugins are deliberately *not* symmetric — they
    /// shape a request one way and a response the other — so they are covered by
    /// their own tests against the reference's peer layouts.
    #[test]
    fn the_full_layer_stack_round_trips() {
        for (method, protocol) in [
            ("aes-256-cfb", SsrProtocol::Origin),
            ("chacha20-ietf", SsrProtocol::AuthSha1V4),
            ("salsa20", SsrProtocol::AuthAes128 { sha1: true }),
        ] {
            let crypto = crypto(method, "pass");
            let iv = crypto.iv.clone();
            let make_proto =
                || SsrProtocolState::new(protocol.clone(), &crypto.key, &iv, "").unwrap();

            // Writer: protocol → cipher, with the IV in front.
            let mut writer_proto = make_proto();
            let mut wire = writer_proto.wrap_data(b"hello world").unwrap();
            let mut write_cipher = crypto.cipher(&iv).unwrap();
            write_cipher.apply(&mut wire);
            let mut wire_with_iv = iv.clone();
            wire_with_iv.extend_from_slice(&wire);
            let mut writer_obfs = SsrObfsState::new(SsrObfs::Plain, 0);
            let on_wire = writer_obfs.wrap(&wire_with_iv, &crypto.key, 7, iv.len());
            assert_eq!(on_wire, wire_with_iv, "plain adds nothing");

            // Reader: obfs → cipher, consuming the IV.
            let mut reader_obfs = SsrObfsState::new(SsrObfs::Plain, 0);
            let mut decoded = reader_obfs.unwrap(&on_wire, &crypto.key).unwrap();

            let peer_iv: Vec<u8> = decoded.drain(..iv.len()).collect();
            assert_eq!(peer_iv, iv, "the IV travels in front of the ciphertext");
            let mut read_cipher = crypto.cipher(&peer_iv).unwrap();
            read_cipher.apply(&mut decoded);
            let mut proto_reader = make_proto();
            let mut out = Vec::new();
            proto_reader.unwrap(&decoded, &mut out).unwrap();
            assert_eq!(out, b"hello world", "{method} / {protocol:?}");
        }
    }

