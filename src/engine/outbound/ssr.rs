/// The 12 bytes both auth protocols put at the head of their first frame:
/// `utc_time` (LE) || client id || connection id (LE).
fn auth_data(local_client_id: &[u8; 4], connection_id: u32) -> Vec<u8> {
    let mut out = Vec::with_capacity(12);
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as u32)
        .unwrap_or(0);
    out.extend_from_slice(&now.to_le_bytes());
    out.extend_from_slice(local_client_id);
    out.extend_from_slice(&connection_id.to_le_bytes());
    out
}

fn random_bytes(len: usize) -> Vec<u8> {
    let mut buf = vec![0u8; len];
    fill_random(&mut buf);
    buf
}

/// A uniform draw below `bound` (0 when `bound` is 0).
fn rand_below(bound: u16) -> usize {
    if bound == 0 {
        return 0;
    }
    let mut raw = [0u8; 2];
    fill_random(&mut raw);
    usize::from(u16::from_be_bytes(raw)) % usize::from(bound)
}

/// A truncated HMAC, which is how every SSR handshake authenticates itself.
fn hmac_truncated<H: Digest>(key: &[u8], data: &[u8], out_len: usize) -> Vec<u8> {
    let mut mac = Hmac::<H>::new(key);
    mac.update(data);
    let mut out = [0u8; 64];
    mac.finalize_into(&mut out);
    out[..out_len].to_vec()
}

/// Which protocol plugin is in use.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SsrProtocol {
    /// Plain Shadowsocks framing: address header, then raw bytes.
    Origin,
    /// `auth_sha1_v4`.
    AuthSha1V4,
    /// `auth_aes128_md5` / `auth_aes128_sha1` (`sha1 = true`).
    AuthAes128 { sha1: bool },
}

impl SsrProtocol {
    /// Parse the plugin name.
    pub fn parse(name: &str) -> Result<Self> {
        match name.trim().to_ascii_lowercase().as_str() {
            "" | "origin" => Ok(Self::Origin),
            "auth_sha1_v4" | "auth_sha1_v4_compatible" => Ok(Self::AuthSha1V4),
            "auth_aes128_md5" => Ok(Self::AuthAes128 { sha1: false }),
            "auth_aes128_sha1" => Ok(Self::AuthAes128 { sha1: true }),
            other @ ("auth_chain_a" | "auth_chain_b" | "auth_chain_c" | "auth_chain_d"
            | "auth_chain_e" | "auth_chain_f") => Err(Error::config(format!(
                "SSR protocol `{other}` is not implemented: its per-frame padding length is \
                 derived from a state the receiver recomputes (a seeded xorshift table), so a \
                 wrong table shifts every byte after the handshake instead of failing loudly; \
                 `auth_aes128_sha1` and `auth_aes128_md5` are the supported equivalents"
            ))),
            other => Err(Error::config(format!(
                "Unknown SSR protocol `{other}`; supported: origin, auth_sha1_v4, \
                 auth_aes128_md5, auth_aes128_sha1"
            ))),
        }
    }

    fn name(&self) -> &'static str {
        match self {
            Self::Origin => "origin",
            Self::AuthSha1V4 => "auth_sha1_v4",
            Self::AuthAes128 { sha1: true } => "auth_aes128_sha1",
            Self::AuthAes128 { sha1: false } => "auth_aes128_md5",
        }
    }
}

/// One protocol instance, both directions — which is how the reference models
/// the *client*: `client_pre_encrypt` out, `client_post_decrypt` in.
struct SsrProtocolState {
    protocol: SsrProtocol,
    /// The cipher key, needed for the handshake MAC and for `auth_aes128`'s
    /// CBC key derivation.
    key: Vec<u8>,
    /// `IV || key` — what authenticates the handshake.
    mac_key: Vec<u8>,
    /// The per-user key: `key`, or `HASH(user_key)` when `protocol-param` is
    /// `uid:userkey`.
    user_key: Vec<u8>,
    /// The uid sent in the `auth_aes128` handshake.
    uid: [u8; 4],
    /// The first frame's fixed 12 bytes.
    auth_data: Vec<u8>,

    sent_header: bool,
    pack_id: u32,
    recv_id: u32,
    recv_buf: Vec<u8>,
}

impl SsrProtocolState {
    fn new(protocol: SsrProtocol, key: &[u8], iv: &[u8], protocol_param: &str) -> Result<Self> {
        let mut mac_key = Vec::with_capacity(iv.len() + key.len());
        mac_key.extend_from_slice(iv);
        mac_key.extend_from_slice(key);

        // `uid:userkey` is the multi-user form: the uid travels in the clear
        // and the key is hashed, so the server can find the user before it can
        // verify anything else.
        let (uid, user_key) = match protocol {
            SsrProtocol::AuthAes128 { sha1 } if protocol_param.contains(':') => {
                let mut parts = protocol_param.splitn(2, ':');
                let uid_number: u32 = parts
                    .next()
                    .unwrap_or("0")
                    .trim()
                    .parse()
                    .map_err(|_| Error::config("SSR protocol-param uid is not a number"))?;
                let secret = parts.next().unwrap_or("");
                let digest = if sha1 {
                    let mut hasher = Sha1::new();
                    hasher.update(secret.as_bytes());
                    hasher.finalize().to_vec()
                } else {
                    let mut hasher = Md5::new();
                    hasher.update(secret.as_bytes());
                    hasher.finalize().to_vec()
                };
                (uid_number.to_le_bytes(), digest)
            }
            _ => {
                let mut uid = [0u8; 4];
                fill_random(&mut uid);
                (uid, key.to_vec())
            }
        };

        let mut local_client_id = [0u8; 4];
        fill_random(&mut local_client_id);
        let connection_id = (u32::from_le_bytes(local_client_id) & 0x00FF_FFFF) + 1;

        Ok(Self {
            protocol,
            key: key.to_vec(),
            mac_key,
            user_key,
            uid,
            auth_data: auth_data(&local_client_id, connection_id),
            sent_header: false,
            pack_id: 1,
            recv_id: 1,
            recv_buf: Vec::new(),
        })
    }

    /// Wrap one chunk of plaintext into protocol frames.
    fn wrap(&mut self, buf: &[u8], head_len: usize) -> Result<Vec<u8>> {
        let mut out = Vec::with_capacity(buf.len() + 64);
        let mut rest = buf;
        if !self.sent_header {
            self.sent_header = true;
            // The first frame keeps the address header together with the
            // handshake plus a random tail, so the header does not end on a
            // frame boundary every time.
            let datalen = buf.len().min(head_len + rand_below(32));
            out.extend_from_slice(&self.wrap_first(&buf[..datalen])?);
            rest = &buf[datalen..];
        }
        while rest.len() > UNIT_LEN {
            out.extend_from_slice(&self.wrap_data(&rest[..UNIT_LEN])?);
            rest = &rest[UNIT_LEN..];
        }
        if !rest.is_empty() || buf.is_empty() {
            out.extend_from_slice(&self.wrap_data(rest)?);
        }
        Ok(out)
    }

    /// The handshake frame (`pack_auth_data`).
    fn wrap_first(&self, payload: &[u8]) -> Result<Vec<u8>> {
        match &self.protocol {
            // No handshake frame: the address header is the first thing the
            // peer reads and the stream is plain Shadowsocks.
            SsrProtocol::Origin => Ok(payload.to_vec()),
            SsrProtocol::AuthSha1V4 => {
                if payload.is_empty() {
                    return Ok(Vec::new());
                }
                // The auth data is *inside* the frame, and the random prefix's
                // length is drawn from the framed length — twelve bytes more
                // than the payload.
                let mut framed = self.auth_data.clone();
                framed.extend_from_slice(payload);
                let mut data = self.rnd_data_sha1(framed.len());
                data.extend_from_slice(&framed);

                let data_len = data.len() + 16;
                let mut crc_input = (data_len as u16).to_be_bytes().to_vec();
                crc_input.extend_from_slice(b"auth_sha1_v4");
                crc_input.extend_from_slice(&self.key);
                let crc = Crc32::compute(&crc_input);

                let mut frame = Vec::with_capacity(data_len);
                frame.extend_from_slice(&(data_len as u16).to_be_bytes());
                frame.extend_from_slice(&crc.to_le_bytes());
                frame.extend_from_slice(&data);
                let mac = hmac_truncated::<Sha1>(&self.mac_key, &frame, 10);
                frame.extend_from_slice(&mac);
                Ok(frame)
            }
            SsrProtocol::AuthAes128 { sha1 } => {
                let sha1 = *sha1;
                if payload.is_empty() {
                    return Ok(Vec::new());
                }
                let rnd_len = if payload.len() > 400 {
                    rand_below(512)
                } else {
                    rand_below(1024)
                };
                // The encrypted block is exactly one AES block: the 12 auth
                // bytes, then the frame length and the random length, both
                // little-endian.
                let data_len = 7 + 4 + 16 + 4 + payload.len() + rnd_len + 4;
                let mut head = self.auth_data.clone();
                head.extend_from_slice(&(data_len as u16).to_le_bytes());
                head.extend_from_slice(&(rnd_len as u16).to_le_bytes());
                debug_assert_eq!(head.len(), 16);

                let mut block = head;
                self.cbc(sha1)?
                    .encrypt(&[0u8; 16], &mut block)
                    .map_err(|_| Error::config("SSR auth_aes128 CBC block"))?;

                let mut body = Vec::with_capacity(31);
                body.extend_from_slice(&self.uid);
                body.extend_from_slice(&block);
                let body_mac = if sha1 {
                    hmac_truncated::<Sha1>(&self.mac_key, &body, 4)
                } else {
                    hmac_truncated::<Md5>(&self.mac_key, &body, 4)
                };
                body.extend_from_slice(&body_mac);

                let mut check_head = [0u8; 1];
                fill_random(&mut check_head);
                let check_mac = if sha1 {
                    hmac_truncated::<Sha1>(&self.mac_key, &check_head, 6)
                } else {
                    hmac_truncated::<Md5>(&self.mac_key, &check_head, 6)
                };

                let mut frame = Vec::with_capacity(data_len);
                frame.extend_from_slice(&check_head);
                frame.extend_from_slice(&check_mac);
                frame.extend_from_slice(&body);
                frame.extend_from_slice(&random_bytes(rnd_len));
                frame.extend_from_slice(payload);
                let tail = if sha1 {
                    hmac_truncated::<Sha1>(&self.user_key, &frame, 4)
                } else {
                    hmac_truncated::<Md5>(&self.user_key, &frame, 4)
                };
                frame.extend_from_slice(&tail);
                debug_assert_eq!(frame.len(), data_len);
                Ok(frame)
            }
        }
    }

    /// The CBC cipher `auth_aes128` encrypts its head block with: the key comes
    /// from `EVP_BytesToKey(base64(user_key) || salt)` and the IV is zero,
    /// which is why the IV prefix the reference drops is not needed on the wire.
    fn cbc(&self, sha1: bool) -> Result<Cbc> {
        let mut material_input =
            courierust::courierust_crypto::base64::encode(&self.user_key).into_bytes();
        material_input.extend_from_slice(if sha1 {
            b"auth_aes128_sha1"
        } else {
            b"auth_aes128_md5"
        });
        let material = evp_bytes_to_key(&material_input, 16, 16);
        Cbc::new(&material[..16]).map_err(|_| Error::config("SSR auth_aes128 CBC key"))
    }

    /// A data frame (`pack_data`).
    fn wrap_data(&mut self, payload: &[u8]) -> Result<Vec<u8>> {
        match &self.protocol {
            SsrProtocol::Origin => Ok(payload.to_vec()),
            SsrProtocol::AuthSha1V4 => {
                let mut data = self.rnd_data_sha1(payload.len());
                data.extend_from_slice(payload);
                let data_len = data.len() + 8;
                let crc = (Crc32::compute(&(data_len as u16).to_be_bytes()) & 0xFFFF) as u16;
                let mut frame = Vec::with_capacity(data_len);
                frame.extend_from_slice(&(data_len as u16).to_be_bytes());
                frame.extend_from_slice(&crc.to_le_bytes());
                frame.extend_from_slice(&data);
                let adler = Adler32::compute(&frame);
                frame.extend_from_slice(&adler.to_le_bytes());
                Ok(frame)
            }
            SsrProtocol::AuthAes128 { sha1 } => {
                let sha1 = *sha1;
                let rnd_len = rand_below(64);
                // `rnd_prefix_aes` writes the random run plus its length field,
                // i.e. `rnd_len + 1` bytes, so the frame is
                // `2 + 2 + (rnd_len + 1) + payload + 4`.
                let data_len = (rnd_len + payload.len() + 9) as u16;
                let mut mac_key = Vec::with_capacity(self.user_key.len() + 4);
                mac_key.extend_from_slice(&self.user_key);
                mac_key.extend_from_slice(&self.pack_id.to_le_bytes());
                self.pack_id = self.pack_id.wrapping_add(1);

                let head_mac = if sha1 {
                    hmac_truncated::<Sha1>(&mac_key, &data_len.to_le_bytes(), 2)
                } else {
                    hmac_truncated::<Md5>(&mac_key, &data_len.to_le_bytes(), 2)
                };
                let mut frame = Vec::with_capacity(usize::from(data_len));
                frame.extend_from_slice(&data_len.to_le_bytes());
                frame.extend_from_slice(&head_mac);
                frame.extend_from_slice(&rnd_prefix_aes(rnd_len));
                frame.extend_from_slice(payload);
                let tail = if sha1 {
                    hmac_truncated::<Sha1>(&mac_key, &frame, 4)
                } else {
                    hmac_truncated::<Md5>(&mac_key, &frame, 4)
                };
                frame.extend_from_slice(&tail);
                debug_assert_eq!(frame.len(), usize::from(data_len));
                Ok(frame)
            }
        }
    }

    /// `auth_sha1_v4`'s random prefix: a length byte, or `0xFF` and a
    /// **big-endian** half-word, followed by that many random bytes.
    fn rnd_data_sha1(&self, buf_size: usize) -> Vec<u8> {
        if buf_size > 1200 {
            return vec![0x01];
        }
        let rnd_len = if buf_size > 400 {
            let mut byte = [0u8; 1];
            fill_random(&mut byte);
            usize::from(byte[0])
        } else {
            rand_below(512)
        };
        let mut out = Vec::with_capacity(rnd_len + 3);
        if rnd_len < 128 {
            out.push((rnd_len + 1) as u8);
        } else {
            out.push(0xFF);
            out.extend_from_slice(&((rnd_len + 3) as u16).to_be_bytes());
        }
        out.extend_from_slice(&random_bytes(rnd_len));
        out
    }

    /// Unwrap a chunk of decrypted bytes, appending whatever frames complete.
    fn unwrap(&mut self, buf: &[u8], out: &mut Vec<u8>) -> Result<()> {
        match self.protocol {
            SsrProtocol::Origin => {
                out.extend_from_slice(buf);
                Ok(())
            }
            SsrProtocol::AuthSha1V4 => self.unwrap_sha1(buf, out),
            SsrProtocol::AuthAes128 { sha1 } => self.unwrap_aes128(buf, out, sha1),
        }
    }

    fn unwrap_sha1(&mut self, buf: &[u8], out: &mut Vec<u8>) -> Result<()> {
        self.recv_buf.extend_from_slice(buf);
        loop {
            if self.recv_buf.len() < 4 {
                break;
            }
            let crc = (Crc32::compute(&self.recv_buf[..2]) & 0xFFFF) as u16;
            if crc.to_le_bytes() != self.recv_buf[2..4] {
                return Err(Error::protocol(
                    "SSR auth_sha1_v4 frame failed its CRC check",
                ));
            }
            let length = usize::from(u16::from_be_bytes([self.recv_buf[0], self.recv_buf[1]]));
            if !(7..MAX_FRAME).contains(&length) {
                return Err(Error::protocol(format!(
                    "SSR auth_sha1_v4 frame length {length} is out of range"
                )));
            }
            if self.recv_buf.len() < length {
                break;
            }
            let frame = self.recv_buf[..length].to_vec();
            let adler = u32::from_le_bytes(frame[length - 4..].try_into().expect("four bytes"));
            if Adler32::compute(&frame[..length - 4]) != adler {
                return Err(Error::protocol(
                    "SSR auth_sha1_v4 frame failed its Adler-32 check",
                ));
            }
            let pos = usize::from(frame[4]);
            let start = if pos < 255 {
                pos + 4
            } else {
                usize::from(u16::from_be_bytes([frame[5], frame[6]])) + 4
            };
            if start > length - 4 {
                return Err(Error::protocol(
                    "SSR auth_sha1_v4 frame is shorter than its own header",
                ));
            }
            out.extend_from_slice(&frame[start..length - 4]);
            self.recv_buf.drain(..length);
            self.recv_id = self.recv_id.wrapping_add(1);
        }
        self.guard_buffer()
    }

    fn unwrap_aes128(&mut self, buf: &[u8], out: &mut Vec<u8>, sha1: bool) -> Result<()> {
        self.recv_buf.extend_from_slice(buf);
        loop {
            if self.recv_buf.len() < 4 {
                break;
            }
            let length = usize::from(u16::from_le_bytes([self.recv_buf[0], self.recv_buf[1]]));
            if !(7..MAX_FRAME).contains(&length) {
                return Err(Error::protocol(format!(
                    "SSR auth_aes128 frame length {length} is out of range"
                )));
            }
            if self.recv_buf.len() < length {
                break;
            }
            let frame = self.recv_buf[..length].to_vec();
            let mut mac_key = Vec::with_capacity(self.user_key.len() + 4);
            mac_key.extend_from_slice(&self.user_key);
            mac_key.extend_from_slice(&self.recv_id.to_le_bytes());

            let head_mac = if sha1 {
                hmac_truncated::<Sha1>(&mac_key, &frame[..2], 2)
            } else {
                hmac_truncated::<Md5>(&mac_key, &frame[..2], 2)
            };
            if head_mac != frame[2..4] {
                return Err(Error::protocol(
                    "SSR auth_aes128 frame failed its length MAC",
                ));
            }
            let tail_mac = if sha1 {
                hmac_truncated::<Sha1>(&mac_key, &frame[..length - 4], 4)
            } else {
                hmac_truncated::<Md5>(&mac_key, &frame[..length - 4], 4)
            };
            if tail_mac != frame[length - 4..] {
                return Err(Error::protocol("SSR auth_aes128 frame failed its MAC"));
            }
            self.recv_id = self.recv_id.wrapping_add(1);

            let pos = usize::from(frame[4]);
            let start = if pos < 255 {
                pos + 4
            } else {
                usize::from(u16::from_le_bytes([frame[5], frame[6]])) + 4
            };
            if start > length - 4 {
                return Err(Error::protocol(
                    "SSR auth_aes128 frame is shorter than its own header",
                ));
            }
            out.extend_from_slice(&frame[start..length - 4]);
            self.recv_buf.drain(..length);
        }
        self.guard_buffer()
    }

    fn guard_buffer(&self) -> Result<()> {
        if self.recv_buf.len() > MAX_PENDING {
            return Err(Error::protocol(
                "SSR peer sent a partial frame larger than the buffer cap",
            ));
        }
        Ok(())
    }
}

/// `auth_aes128`'s random prefix: a length byte, or `0xFF` and a
/// **little-endian** half-word, and that many random bytes.
///
/// Note the endianness: this family writes the escape length little-endian
/// where `auth_sha1_v4` writes it big-endian. Two protocols, two rules.
///
/// The long form's length field counts the two length bytes, so the random run
/// is two bytes shorter than the value written — which is what makes both forms
/// `rnd_len + 1` bytes and lets the reader use one skip rule.
fn rnd_prefix_aes(rnd_len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(rnd_len + 1);
    if rnd_len < 128 {
        out.push((rnd_len + 1) as u8);
        out.extend_from_slice(&random_bytes(rnd_len));
    } else {
        out.push(0xFF);
        out.extend_from_slice(&((rnd_len + 1) as u16).to_le_bytes());
        out.extend_from_slice(&random_bytes(rnd_len.saturating_sub(2)));
    }
    out
}

