    /// The `tls1.2_ticket_auth` first packet: a ClientHello record, the CCS and
    /// Finished records, the MAC over exactly those two, then the payload in an
    /// application-data record.
    #[test]
    fn the_tls_obfs_first_packet_is_shaped_like_the_reference() {
        let mut obfs = SsrObfsState::new(
            SsrObfs::Tls12TicketAuth {
                host: "www.bing.com".to_string(),
            },
            443,
        );
        let key = b"0123456789abcdef";
        let payload = b"the first cipher bytes".to_vec();
        let out = obfs.wrap(&payload, key, 15, 16);

        assert_eq!(&out[0..3], &[0x16, 0x03, 0x01], "a handshake record");
        let hello_len = usize::from(u16::from_be_bytes([out[3], out[4]]));
        assert_eq!(out[5], 0x01, "a ClientHello");
        // The handshake length is three bytes long, so the record is four bytes
        // longer than the value they hold.
        let hs_len = (usize::from(out[6]) << 16) | (usize::from(out[7]) << 8) | usize::from(out[8]);
        assert_eq!(hs_len + 4, hello_len, "the handshake length matches");
        assert_eq!(&out[9..11], &[0x03, 0x03], "TLS 1.2 body version");
        assert_eq!(out[43], 0x20, "a 32-byte session id");

        // Right after the version: the time and random bytes, the MAC over
        // exactly those, then the session id the peer must echo.
        let auth = &out[11..43];
        let mac = hmac_truncated::<Sha1>(&obfs.tls_mac_key(key), &auth[..22], 10);
        assert_eq!(&auth[22..32], &mac[..], "the MAC covers time || random");
        assert_eq!(&out[44..76], &obfs.client_id[..], "the client id follows");
        assert!(
            out[..hello_len + 5]
                .windows(b"www.bing.com".len())
                .any(|w| w == b"www.bing.com"),
            "the SNI is in the extensions"
        );

        let tail = &out[hello_len + 5..];
        assert_eq!(&tail[0..6], &[0x14, 0x03, 0x03, 0x00, 0x01, 0x01]);
        assert_eq!(&tail[6..11], &[0x16, 0x03, 0x03, 0x00, 0x20]);
        // The MAC covers the CCS record and the Finished record as sent, which
        // is 33 bytes — not the 32 the Finished declares.
        let tail_mac = hmac_truncated::<Sha1>(&obfs.tls_mac_key(key), &tail[..33], 10);
        assert_eq!(&tail[33..43], &tail_mac[..]);

        let records = &tail[43..];
        assert_eq!(&records[0..3], &[0x17, 0x03, 0x03]);
        let record_len = usize::from(u16::from_be_bytes([records[3], records[4]]));
        assert_eq!(&records[5..5 + record_len], &payload[..]);
    }

    #[test]
    fn tls_obfs_records_round_trip_and_wait_for_their_tail() {
        let buf: Vec<u8> = (0..5000u32).map(|i| i as u8).collect();
        let wire = tls_records(&buf);

        // Walking the records must rebuild the input, and no record may be
        // empty or past the cap the record layer can name.
        let mut rest = &wire[..];
        let mut decoded = Vec::new();
        while !rest.is_empty() {
            assert_eq!(&rest[..3], &[0x17, 0x03, 0x03]);
            let len = usize::from(u16::from_be_bytes([rest[3], rest[4]]));
            assert!((1..=4195).contains(&len), "a record of {len} bytes");
            decoded.extend_from_slice(&rest[5..5 + len]);
            rest = &rest[5 + len..];
        }
        assert_eq!(decoded, buf);

        let mut obfs = SsrObfsState::new(
            SsrObfs::Tls12TicketAuth {
                host: "h".to_string(),
            },
            443,
        );
        // The data phase on its own: the handshake has its own test.
        obfs.unwrapped = true;
        let (head, tail) = wire.split_at(7);
        assert!(obfs.unwrap(head, b"key").unwrap().is_empty());
        assert_eq!(obfs.unwrap(tail, b"key").unwrap(), buf);

        // A record whose type is not application data is not a stream.
        let mut obfs = SsrObfsState::new(
            SsrObfs::Tls12TicketAuth {
                host: "h".to_string(),
            },
            443,
        );
        obfs.unwrapped = true;
        assert!(obfs
            .unwrap(&[0x99, 0x03, 0x03, 0x00, 0x00], b"key")
            .is_err());
    }

    /// The peer's half of `tls1.2_ticket_auth`, built from the reference's
    /// `server_encode`: a `ServerHello`, a `ChangeCipherSpec`, a `Finished`, the
    /// MAC that seals those three, then the payload in data records.
    fn server_handshake(key: &[u8], client_id: &[u8; 32], payload: &[u8]) -> Vec<u8> {
        let mut mac_key = key.to_vec();
        mac_key.extend_from_slice(client_id);

        // time || random, then the MAC over exactly those 22 bytes.
        let mut auth = vec![0x11, 0x22, 0x33, 0x44];
        auth.extend_from_slice(&random_bytes(18));
        auth.extend_from_slice(&hmac_truncated::<Sha1>(&mac_key, &auth, 10));
        assert_eq!(auth.len(), 32);

        let mut body = vec![0x03, 0x03];
        body.extend_from_slice(&auth);
        body.push(0x20);
        body.extend_from_slice(&client_id[..]);
        body.extend_from_slice(&[0xc0, 0x2f, 0x00, 0x00, 0x05, 0xff, 0x01, 0x00, 0x01, 0x00]);

        let mut out = vec![0x16, 0x03, 0x03];
        let mut hello = vec![0x02, 0x00];
        hello.extend_from_slice(&(body.len() as u16).to_be_bytes());
        hello.extend_from_slice(&body);
        out.extend_from_slice(&(hello.len() as u16).to_be_bytes());
        out.extend_from_slice(&hello);

        out.extend_from_slice(&[0x14, 0x03, 0x03, 0x00, 0x01, 0x01]);
        // Declares 32 bytes and sends 22, exactly as the reference does.
        out.extend_from_slice(&[0x16, 0x03, 0x03, 0x00, 0x20]);
        out.extend_from_slice(&random_bytes(22));
        let seal = hmac_truncated::<Sha1>(&mac_key, &out, 10);
        out.extend_from_slice(&seal);
        out.extend_from_slice(&tls_records(payload));
        out
    }

    /// A handshake built to the reference's own layout is accepted, and the
    /// first data record behind it becomes the reader's payload.
    #[test]
    fn the_fabricated_server_handshake_is_verified_and_its_payload_recovered() {
        let key = b"the obfs key";
        let mut obfs = SsrObfsState::new(
            SsrObfs::Tls12TicketAuth {
                host: "www.bing.com".to_string(),
            },
            443,
        );
        let wire = server_handshake(key, &obfs.client_id, b"first bytes");

        // Split across reads: nothing before the MAC has been checked.
        let (head, tail) = wire.split_at(20);
        assert!(obfs.unwrap(head, key).unwrap().is_empty());
        assert_eq!(obfs.unwrap(tail, key).unwrap(), b"first bytes");

        // Data records keep flowing afterwards.
        assert_eq!(obfs.unwrap(&tls_records(b"more"), key).unwrap(), b"more");
    }

    /// Every MAC in that handshake is load-bearing, and so is the echo of the
    /// session id.
    #[test]
    fn a_tampered_server_handshake_is_rejected() {
        let key = b"the obfs key";
        // 12: inside the MAC input. 35: the ServerHello's own MAC. 50: inside
        // the echoed session id. 122: the seal over the whole handshake.
        for offset in [12usize, 35, 50, 122] {
            let mut obfs = SsrObfsState::new(
                SsrObfs::Tls12TicketAuth {
                    host: "h".to_string(),
                },
                443,
            );
            let mut wire = server_handshake(key, &obfs.client_id, b"");
            wire[offset] ^= 0x40;
            assert!(
                obfs.unwrap(&wire, key).is_err(),
                "a flip at offset {offset} must be caught"
            );
        }
    }

    /// The peer's half of the HTTP obfs, from the reference's
    /// `server_decode`: the request line's escaped bytes are decoded and put in
    /// front of the body.
    fn uri_head_bytes(wire: &[u8]) -> Vec<u8> {
        let line_end = wire
            .iter()
            .position(|b| *b == b'\r')
            .expect("a complete request line");
        let mut out = Vec::new();
        for item in wire[..line_end].split(|b| *b == b'%').skip(1) {
            // The reference stops at the first item that is not a clean pair,
            // which is how the trailing ` HTTP/1.1` is dropped.
            if item.len() < 2 {
                break;
            }
            let pair = core::str::from_utf8(&item[..2]).expect("hex is ASCII");
            out.push(u8::from_str_radix(pair, 16).expect("hex"));
            if item.len() > 2 {
                break;
            }
        }
        out
    }

    fn server_decode_http(wire: &[u8]) -> Vec<u8> {
        let head_end = find_head_end(wire).expect("a complete head");
        let mut out = uri_head_bytes(wire);
        out.extend_from_slice(&wire[head_end..]);
        out
    }

    #[test]
    fn a_config_without_the_required_fields_is_refused() {
        let build = |options: &[(&str, nextjson::Value)]| {
            let mut map = std::collections::HashMap::new();
            for (k, v) in options {
                map.insert((*k).to_string(), v.clone());
            }
            SsrOutbound::new(OutboundConfig {
                tag: "ssr".to_string(),
                outbound_type: crate::engine::config::OutboundType::ShadowsocksR,
                server: Some("127.0.0.1".to_string()),
                port: Some(1),
                options: map,
            })
            .map(|_| ())
            .map_err(|e| e.to_string())
        };
        let string = |s: &str| nextjson::Value::String(s.to_string());

        assert!(build(&[]).unwrap_err().contains("cipher"));
        assert!(build(&[("cipher", string("aes-256-cfb"))])
            .unwrap_err()
            .contains("password"));
        assert!(build(&[("cipher", string("aes-256-cfb")), ("password", string("x"))]).is_ok());
        // The refusals surface through the outbound constructor too.
        assert!(build(&[
            ("cipher", string("aes-256-cfb")),
            ("password", string("x")),
            ("protocol", string("auth_chain_a"))
        ])
        .unwrap_err()
        .contains("xorshift"));
    }

