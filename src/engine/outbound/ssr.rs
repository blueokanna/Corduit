/// A relayed SSR connection as a duplex stream.
///
/// The layers are applied in the order the module documents; the only state the
/// stream adds on top is the buffer bookkeeping that lets a frame or a record
/// arrive split across reads.
struct SsrStream {
    inner: BoxStream,
    crypto: SsrCrypto,
    /// Built once the peer's IV has arrived (immediately when it sends none).
    read_cipher: Option<SsrCipher>,
    write_cipher: SsrCipher,
    iv_sent: bool,
    proto: SsrProtocolState,
    obfs: SsrObfsState,
    /// Obfs-decoded bytes not yet decrypted, or holding the peer's IV.
    incoming: Vec<u8>,
    /// Plaintext ready for the caller.
    ready: Vec<u8>,
    ready_pos: usize,
    /// The address header's length, which the first frame and the HTTP head
    /// both need.
    head_len: usize,
}

impl SsrStream {
    fn new(
        inner: BoxStream,
        method: SsrMethod,
        password: &[u8],
        protocol: SsrProtocol,
        obfs: SsrObfs,
        protocol_param: &str,
        server_port: u16,
    ) -> Result<Self> {
        let crypto = SsrCrypto::new(method, password);
        let write_cipher = crypto.cipher(&crypto.iv)?;
        let read_cipher = if method.iv_len() == 0 {
            Some(crypto.cipher(&[])?)
        } else {
            None
        };
        let proto = SsrProtocolState::new(protocol, &crypto.key, &crypto.iv, protocol_param)?;
        Ok(Self {
            inner,
            crypto,
            read_cipher,
            write_cipher,
            iv_sent: false,
            proto,
            obfs: SsrObfsState::new(obfs, server_port),
            incoming: Vec::new(),
            ready: Vec::new(),
            ready_pos: 0,
            head_len: 0,
        })
    }

    /// Send the address header (and any first payload) as the handshake.
    fn send_header(&mut self, target: &TargetAddr, first_payload: &[u8]) -> Result<()> {
        let header = address_header(target)?;
        self.head_len = address_header_len(&header);
        let mut first = header;
        first.extend_from_slice(first_payload);
        self.write_all(&first)
            .map_err(|e| Error::network(format!("SSR handshake failed: {e}")))
    }

    /// Decrypt and un-frame whatever `incoming` holds; `Ok(false)` when it needs
    /// more bytes first.
    fn drain_incoming(&mut self) -> Result<bool> {
        if self.read_cipher.is_none() {
            let iv_len = self.crypto.method.iv_len();
            if self.incoming.len() < iv_len {
                return Ok(false);
            }
            let iv: Vec<u8> = self.incoming.drain(..iv_len).collect();
            self.read_cipher = Some(self.crypto.cipher(&iv)?);
        }
        if self.incoming.is_empty() {
            return Ok(false);
        }
        let mut buf = std::mem::take(&mut self.incoming);
        self.read_cipher
            .as_mut()
            .expect("built above")
            .apply(&mut buf);
        self.proto.unwrap(&buf, &mut self.ready)?;
        Ok(true)
    }
}

impl Read for SsrStream {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        loop {
            if self.ready_pos < self.ready.len() {
                let take = (self.ready.len() - self.ready_pos).min(buf.len());
                buf[..take].copy_from_slice(&self.ready[self.ready_pos..self.ready_pos + take]);
                self.ready_pos += take;
                if self.ready_pos == self.ready.len() {
                    self.ready.clear();
                    self.ready_pos = 0;
                }
                return Ok(take);
            }
            self.ready.clear();
            self.ready_pos = 0;

            if !self.incoming.is_empty() {
                match self.drain_incoming() {
                    Ok(true) => continue,
                    Ok(false) => {}
                    Err(e) => return Err(std::io::Error::other(e.to_string())),
                }
            }

            let mut tmp = [0u8; 16 * 1024];
            // A read timeout propagates: the relay treats it as "nothing yet"
            // and re-polls, which is how a blocking stream stays cancellable.
            let n = self.inner.read(&mut tmp)?;
            if n == 0 {
                return Ok(0);
            }
            let decoded = self
                .obfs
                .unwrap(&tmp[..n], &self.crypto.key)
                .map_err(|e| std::io::Error::other(e.to_string()))?;
            self.incoming.extend_from_slice(&decoded);
        }
    }
}

impl Write for SsrStream {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        let framed = self
            .proto
            .wrap(buf, self.head_len)
            .map_err(|e| std::io::Error::other(e.to_string()))?;
        let mut payload = framed;
        self.write_cipher.apply(&mut payload);

        let iv_len = self.crypto.iv.len();
        let mut wire = Vec::with_capacity(payload.len() + iv_len + 64);
        if !self.iv_sent {
            wire.extend_from_slice(&self.crypto.iv);
            self.iv_sent = true;
        }
        wire.extend_from_slice(&payload);
        let wire = self
            .obfs
            .wrap(&wire, &self.crypto.key, self.head_len, iv_len);
        self.inner.write_all(&wire)?;
        Ok(buf.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        self.inner.flush()
    }
}

impl SyncStream for SsrStream {
    fn shutdown(&self, how: Shutdown) -> std::io::Result<()> {
        // SSR's protocols have no end-of-stream frame: the only way to say
        // "done writing" would be a TCP FIN, which the peer reads as the whole
        // session ending and would kill the response half still in flight.
        // A full close is forwarded.
        if how == Shutdown::Both {
            self.inner.shutdown(how)
        } else {
            Ok(())
        }
    }

    fn peer_addr(&self) -> Option<SocketAddr> {
        self.inner.peer_addr()
    }

    fn set_read_timeout(&self, timeout: Option<Duration>) -> std::io::Result<()> {
        self.inner.set_read_timeout(timeout)
    }

    fn set_write_timeout(&self, timeout: Option<Duration>) -> std::io::Result<()> {
        self.inner.set_write_timeout(timeout)
    }
}

