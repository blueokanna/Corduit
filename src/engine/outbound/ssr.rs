//! ShadowsocksR outbound.
//!
//! SSR is Shadowsocks with two plugins stacked around the cipher. The wire
//! order is what makes it confusing, and getting it backwards costs hours, so
//! it is stated once here and never again:
//!
//! ```text
//! client ──► plaintext ──► [protocol] ──► [cipher] ──► [obfs] ──► wire
//! client ◄── plaintext ◄── [protocol] ◄── [cipher] ◄── [obfs] ◄── wire
//! ```
//!
//! * **protocol** frames the stream and carries the handshake. It sees
//!   plaintext, and on the client it needs the cipher's IV before it can build
//!   its first frame — `auth_sha1_v4`'s HMAC key is `IV || key` — which is why
//!   the IV is generated first and prepended outside the cipher.
//! * **cipher** is a stream cipher with the IV in front of the first packet.
//! * **obfs** wraps the first packet in a fake HTTP or TLS exchange. For
//!   `tls1.2_ticket_auth` it keeps wrapping every packet in a TLS
//!   application-data record afterwards; the others pass bytes through.
//!
//! Addresses use the Shadowsocks encoding (`0x01` IPv4 / `0x03` domain /
//! `0x04` IPv6, then the port big-endian) through the same
//! [`crate::protocol::Address`] encoder the Shadowsocks outbound uses.
//!
//! # Where the layouts come from
//!
//! SSR has no specification. Every frame below comes from
//! `shadowsocksr-live/shadowsocksr`:
//!
//! | piece | reference |
//! |---|---|
//! | `origin` | identity — the stream is plain Shadowsocks framing |
//! | `auth_sha1_v4` | `obfsplugin/auth.py` · `pack_auth_data`, `pack_data`, `rnd_data` |
//! | `auth_aes128_md5` / `auth_aes128_sha1` | `obfsplugin/auth.py` · `auth_aes128_sha1` |
//! | `plain`, `http_simple`, `http_post` | `obfsplugin/plain.py`, `obfsplugin/http_simple.py` |
//! | `tls1.2_ticket_auth` | `obfsplugin/obfs_tls.py` |
//! | cipher table and `EVP_BytesToKey` | `crypto/{openssl,rc4_md5}.py`, `encrypt.py` |
//!
//! # Deliberate refusals, each with its reason
//!
//! * **`auth_chain_a` / `auth_chain_b`.** Their per-frame padding length is not
//!   transmitted: the receiver recomputes it from the running HMAC and a table
//!   generated by a seeded xorshift128+. A wrong table does not fail loudly —
//!   it shifts every byte after the handshake, which looks exactly like a
//!   broken server. Refused at construction, with the reason in the message.
//! * **`random_head`.** Its first packet is verifiable (`urandom(u8 % 96 + 4)`
//!   followed by `LE32(0xffffffff - crc32(random))`), but the plugin also holds
//!   the client's stream back until the server's own random packet arrives.
//!   That needs a second buffer on the write path — the relay's first write
//!   cannot go out until the peer answers — and half-wiring it would stall the
//!   request instead of shaping it. Refused by name rather than shipped
//!   broken.
//! * **`table`.** An 8-bit substitution table with no key and no IV: not
//!   encryption at all.
//! * **AEAD methods** (`aes-*-gcm`, `chacha20-ietf-poly1305`, …) are refused
//!   with a pointer at the `shadowsocks` outbound, which implements AEAD
//!   framing properly; SSR's plugin semantics on top of AEAD are a different
//!   cipher path, and half-supporting it would be worse than saying so.
//! * **The exotic block ciphers** (`bf-cfb`, `camellia-*-cfb`, `cast5-cfb`,
//!   `des-cfb`, `idea-cfb`, `rc2-cfb`, `seed-cfb`) are refused by name:
//!   supporting them means porting four more block ciphers for a wire format
//!   nobody has deployed in a decade.
//! * **UDP** is refused. SSR's UDP path applies a protocol-specific frame over
//!   the same obfs, and that framing is *stateful* (connection ids, replay
//!   windows) — the engine's one-shot UDP API has nowhere to keep it, so
//!   accepting the config would mean dropping DNS rather than tunnelling it.
//!
//! # The obfs layer, and the two things it is easy to get wrong
//!
//! * `http_simple` / `http_post` move `iv_len + head_len` bytes — plus up to 64
//!   more — out of the body and into the request line, percent-escaped, so the
//!   IV and the address header do not sit at a fixed offset a middlebox could
//!   count. The *server* decodes those bytes and puts them back in front of the
//!   body, which is why a client that only stripped heads would lose its own
//!   first bytes. That split is what `wrap`'s header and IV lengths are for.
//! * `tls1.2_ticket_auth` fabricates a handshake in both directions: a
//!   `ClientHello` whose 32-byte session id is the client id that salts every
//!   MAC, then a `ChangeCipherSpec` and a `Finished`, then a 10-byte MAC over
//!   those two records. The peer's `Finished` *declares* ten more payload bytes
//!   than it sends, and both readers subtract exactly ten — a reader that
//!   trusted the declared length would walk off the record. After the
//!   handshake the stream is `17 03 03 || u16 length || payload` with no
//!   per-frame MAC: authentication comes from the cipher, not the obfs.
//!   The peer's handshake is verified — its `ServerHello` MAC, the echo of our
//!   session id, and the seal over the whole handshake — and a mismatch aborts
//!   the connection. The reference answers with a 2048-byte decoy instead, to
//!   look like a web server that failed; this build drops the connection
//!   rather than impersonate one.
//!
//! # Deviations from the reference, stated
//!
//! * **Padding length policy.** `auth_sha1_v4` draws 1, `u8 % 256` or
//!   `u16BE % 512` bytes exactly as the reference does, and the framed length
//!   makes every one of those forms self-describing. `auth_aes128_*` draws a
//!   small uniform value where the reference aims its draw at a moving MSS
//!   estimate with a trapezoid distribution; the framing is identical, so a
//!   peer accepts either, and the traffic-shaping strength differs.
//! * **The first frame's split point** uses the real address-header length
//!   instead of the reference's 30-byte estimate, so the header always lands
//!   inside the first frame.
//! * **The `tls1.2_ticket_auth` client id** is fresh per connection; the
//!   reference reuses one per process. Nothing on the wire distinguishes the
//!   two — the id travels in the session id field either way — and the server's
//!   replay window never sees a repeat.
//! * **`obfs_param`'s embedded body template** (a fake HTML document after a
//!   `#` in the host parameter) is not emitted: the profile's `obfs-host` is
//!   used as a host list, which is the part that changes who the traffic looks
//!   like it is for.
//!
//! # Padding in `auth_sha1_v4` and `auth_aes128_*`
//!
//! Both carry a random-length prefix on every frame, and its *length is
//! transmitted* (a byte with a `0xFF` escape, or a half-word). The receiver
//! therefore never has to reproduce the sender's policy, which is what makes a
//! different policy safe: the prefix value is always the prefix's own length, so
//! the reader lands on the first payload byte whatever the sender chose.

